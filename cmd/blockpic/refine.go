package main

import (
	"flag"
	"fmt"
	"io/ioutil"
	"os"

	"github.com/filmil/blockpic/pkg/parser"
	"github.com/filmil/blockpic/pkg/refine"
	"github.com/filmil/blockpic/pkg/scanner"
)

func refineCmd() {
	refineFlags := flag.NewFlagSet("refine", flag.ExitOnError)
	inputSvg := refineFlags.String("svg", "", "Input SVG file generated by netlistsvg")
	output := refineFlags.String("o", "refined.svg", "Output refined SVG file")

	if len(os.Args) < 4 {
		fmt.Println("Usage: blockpic refine <file.blockpic> -svg <input.svg> [-o refined.svg]")
		os.Exit(1)
	}

	file := os.Args[2]
	refineFlags.Parse(os.Args[3:])

	if *inputSvg == "" {
		fmt.Println("Error: -svg flag is required")
		os.Exit(1)
	}

	content, err := ioutil.ReadFile(file)
	if err != nil {
		fmt.Printf("Error reading blockpic file: %v\n", err)
		os.Exit(1)
	}

	svgBytes, err := ioutil.ReadFile(*inputSvg)
	if err != nil {
		fmt.Printf("Error reading SVG file: %v\n", err)
		os.Exit(1)
	}

	s := scanner.New(string(content))
	p := parser.New(s)
	diag := p.ParseDiagram()

	if len(p.Errors()) > 0 {
		fmt.Println("Parser errors:")
		for _, err := range p.Errors() {
			fmt.Printf(" - %s\n", err)
		}
		os.Exit(1)
	}

	refinedSvg, err := refine.Process(diag, svgBytes)
	if err != nil {
		fmt.Printf("Error refining SVG: %v\n", err)
		os.Exit(1)
	}

	if err := ioutil.WriteFile(*output, refinedSvg, 0644); err != nil {
		fmt.Printf("Error saving file: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Successfully generated refined SVG to %s\n", *output)
}
